"""Build ``data/STATS.md``: the derivation funnel and its rates.

Every number here is computed from the same run that wrote the committed derived files,
so the file is the provenance record for the counts in the README and the page. It is
written deterministically (no timestamp, sorted groups, one decimal place).
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from typing import Any

from field_return_triage.contracts import Complaint
from field_return_triage.data.complaints import (
    ResolutionStats,
    ScreenResult,
    coded_safety_row,
    split_half,
)
from field_return_triage.data.recalls import RecallResolutionStats

__all__ = ["StatsInput", "build_stats"]


@dataclass(frozen=True)
class StatsInput:
    """Everything the statistics file needs, captured from one derivation."""

    snapshot: str
    groups: tuple[str, ...]
    resolution: ResolutionStats
    screen: ScreenResult
    library: Sequence[Complaint]
    eval_items: Sequence[Complaint]
    test_pool: Sequence[dict[str, Any]]
    recalls: RecallResolutionStats


def _pct(numerator: int, denominator: int) -> str:
    if denominator == 0:
        return "n/a"
    return f"{100.0 * numerator / denominator:.1f}%"


def _safety(items: Iterable[Complaint]) -> int:
    return sum(1 for item in items if item.coded_safety)


def _pool_safety(rows: Iterable[dict[str, Any]]) -> int:
    return sum(1 for row in rows if coded_safety_row(row))


def _table(header: Sequence[str], rows: Iterable[Sequence[object]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(value) for value in row) + " |")
    return lines


def build_stats(source: StatsInput) -> str:
    """Render the deterministic Markdown statistics file."""
    resolution = source.resolution
    screen = source.screen
    library = list(source.library)
    eval_items = list(source.eval_items)
    test_pool = list(source.test_pool)
    groups = tuple(source.groups)

    pool_counts = Counter(str(row.get("component_group")) for row in test_pool)
    library_counts = Counter(item.group for item in library if item.group)
    eval_counts = Counter(item.group for item in eval_items if item.group)
    eval_safety = Counter(item.group for item in eval_items if item.group and item.coded_safety)

    wam_rows = [row for row in test_pool if split_half(str(row.get("ODINO"))) == "wam"]
    frt_rows = [row for row in test_pool if split_half(str(row.get("ODINO"))) == "frt"]

    lines: list[str] = [
        "# Data statistics",
        "",
        f"Snapshot: {source.snapshot}. Generated by `make data`; do not edit by hand.",
        "Every count below comes from the same run that wrote the committed derived files.",
        "",
        "## Derivation funnel",
        "",
    ]
    lines += _table(
        ("Step", "Rows / complaints"),
        [
            ("Parsed complaint rows", resolution.parsed_rows),
            ("Vehicle complaint rows", resolution.vehicle_rows),
            ("Vehicle complaints", resolution.vehicle_complaints),
            ("Single-group complaints", resolution.single_group_complaints),
            ("Dropped: narrative under 80 characters", screen.length_dropped),
            ("Dropped: PII screen", screen.pii_dropped),
            ("Library items (2020-2024, cap 20,000)", len(library)),
            ("Evaluation items (2025-2026, frt half)", len(eval_items)),
        ],
    )
    lines += ["", "## Counts per group", ""]
    lines += _table(
        (
            "Group",
            "Test pool",
            "wam half",
            "frt half",
            "Library",
            "Evaluation",
        ),
        [
            (
                group,
                pool_counts.get(group, 0),
                sum(1 for row in wam_rows if row.get("component_group") == group),
                sum(1 for row in frt_rows if row.get("component_group") == group),
                library_counts.get(group, 0),
                eval_counts.get(group, 0),
            )
            for group in groups
        ]
        + [
            (
                "**Total**",
                len(test_pool),
                len(wam_rows),
                len(frt_rows),
                len(library),
                len(eval_items),
            )
        ],
    )
    lines += [
        "",
        "Counts in the test pool and both halves are after the single-group rule, the",
        "80-character minimum and the PII screen, which is the sampling pool. The weekly",
        "trend table is counts-only and is **not** filtered by narrative length or PII.",
        "",
        "## Safety (coded crash / fire / injury or death)",
        "",
    ]
    pool_total = len(test_pool)
    pool_safe = _pool_safety(test_pool)
    frt_safe = _pool_safety(frt_rows)
    lines += _table(
        ("Set", "Items", "Safety-relevant", "Rate"),
        [
            ("Test pool, natural (2025-2026)", pool_total, pool_safe, _pct(pool_safe, pool_total)),
            ("frt half, natural (sampling pool)", len(frt_rows), frt_safe, _pct(frt_safe, len(frt_rows))),
            (
                "Evaluation sample (oversampled)",
                len(eval_items),
                _safety(eval_items),
                _pct(_safety(eval_items), len(eval_items)),
            ),
            (
                "Library (2020-2024, natural)",
                len(library),
                _safety(library),
                _pct(_safety(library), len(library)),
            ),
        ],
    )
    lines += [
        "",
        "The evaluation sample is safety-oversampled to at least 80 of 400 items; the",
        "natural rate is the pool rate before sampling. Both are reported so neither can",
        "be mistaken for the other.",
        "",
        "## Per-group safety in the evaluation sample",
        "",
    ]
    lines += _table(
        ("Group", "Items", "Safety-relevant", "Rate"),
        [
            (
                group,
                eval_counts.get(group, 0),
                eval_safety.get(group, 0),
                _pct(eval_safety.get(group, 0), eval_counts.get(group, 0)),
            )
            for group in groups
        ],
    )
    lines += ["", "## PII screen", ""]
    lines += _table(
        ("Pattern", "Narratives dropped"),
        [(name, count) for name, count in screen.pii_by_pattern.items()]
        + [("**Any pattern** (overlapping)", screen.pii_dropped)],
    )
    lines += [
        "",
        "A narrative is dropped whole when any pattern matches; nothing is redacted in",
        "place. The per-pattern counts overlap, so they add up to more than the any-pattern",
        "count.",
        "",
        "## Recall mapping",
        "",
    ]
    recalls = source.recalls
    lines += _table(
        ("Measure", "Count", "Rate"),
        [
            ("Recall rows parsed", recalls.parsed_rows, ""),
            ("Vehicle recall rows", recalls.vehicle_rows, _pct(recalls.vehicle_rows, recalls.parsed_rows)),
            ("Mapped recall rows", recalls.mapped_rows, _pct(recalls.mapped_rows, recalls.vehicle_rows)),
            ("Vehicle recall campaigns", recalls.vehicle_campaigns, ""),
            (
                "Mapped recall campaigns",
                recalls.mapped_campaigns,
                _pct(recalls.mapped_campaigns, recalls.vehicle_campaigns),
            ),
        ],
    )
    lines += [
        "",
        "The mapped share is reported, not forced: the unmapped rows name components with",
        "no prefix in `data/groups.toml` (mostly mechanical, tyre and equipment families).",
        "",
    ]
    return "\n".join(lines)
